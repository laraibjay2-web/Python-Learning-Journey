# Your task is to build a calculator that:

# Asks the user for two numbers.
# Performs all seven operations.
# Displays the results clearly


first_num = int(input("Enter first number:"))
second_num= int(input("Enter second number:"))

print("addition:",first_num + second_num )
print("subtract:",first_num - second_num )
print("multiplicaton:",first_num * second_num )
print("division:",first_num / second_num )
print("remainder:",first_num % second_num )
print("power:",first_num ** second_num )
print("floor division:",first_num // second_num )